test('tooltip opens on hover after a short delay, on focus at once, and closes on Escape', async ({ page }) => {
  await page.goto('/docs/tooltip')
  const root = page.locator('.apogee-tooltip').first()
  const panel = root.locator('[role="tooltip"]')
  await root.hover()
  await expect(panel).not.toBeVisible()
  await expect(panel).toBeVisible({ timeout: 1500 })
  await settled(panel)
  const t = await root.boundingBox(), p = await panel.boundingBox()
  expect(p.y + p.height).toBeLessThanOrEqual(t.y + 1)
  await page.mouse.move(0, 0)
  await expect(panel).not.toBeVisible()
  await root.locator('button, a').first().focus()
  await expect(panel).toBeVisible({ timeout: 200 })
  await page.keyboard.press('Escape')
  await expect(panel).not.toBeVisible()
  expect(await root.locator('button, a').first().getAttribute('aria-describedby')).toBe(await panel.getAttribute('id'))
})

