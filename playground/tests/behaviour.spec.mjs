test('custom select: keyboard choice updates the native select, fires change and submits with the form', async ({ page }) => {
  await page.goto('/docs/select')
  const root = page.locator('.apogee-select[data-custom]').first()
  const native = root.locator('select')
  const trigger = root.locator('button[aria-haspopup="listbox"]')
  await expect(native).toBeHidden()
  await page.evaluate(() => { window.__changed = 0; document.addEventListener('change', () => window.__changed++, true) })
  await trigger.click()
  const list = page.locator(`#${await trigger.getAttribute('aria-controls')}`)
  await expect(list).toBeVisible()
  await expect(list.locator('[role="option"]').first()).toBeFocused() // opening focuses the current option
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(list).not.toBeVisible()
  // Focus opens on the first enabled option; two ArrowDowns land on the third listbox option.
  const picked = list.locator('[role="option"]').nth(2)
  const expected = await picked.getAttribute('data-value')
  expect(await native.inputValue()).toBe(expected)
  expect(await page.evaluate(() => window.__changed)).toBe(1)
  await expect(trigger).toContainText(await picked.getAttribute('data-label'))
  const name = await native.getAttribute('name')
  expect(await root.evaluate((r, n) => new FormData(r.closest('form')).get(n), name)).toBe(expected)
  // Clicking the field label focuses the trigger, not the hidden select.
  await page.locator(`label[for="${await native.getAttribute('id')}"]`).click()
  await expect(trigger).toBeFocused()
})

