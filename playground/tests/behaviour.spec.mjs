test('dropdown: arrow opens and focuses, item click closes with one close event, submenu via ArrowRight', async ({ page }) => {
  await page.goto('/docs/dropdown')
  const root = page.locator('.apogee-dropdown', { has: page.locator('.apogee-dropdown-sub') }).first()
  const trigger = root.locator('> button')
  const menu = root.locator('> [role="menu"]')
  await page.evaluate(() => { window.__closes = 0; document.addEventListener('apogee:dropdown-close', () => window.__closes++) })
  await trigger.focus()
  await trigger.press('ArrowDown')
  await expect(menu).toBeVisible()
  await expect(menu.locator('[role="menuitem"]').first()).toBeFocused()
  const subTrigger = root.locator('.apogee-dropdown-sub > [role="menuitem"]').first()
  await subTrigger.focus()
  await subTrigger.press('ArrowRight')
  const sub = root.locator('.apogee-dropdown-sub > [role="menu"]').first()
  await expect(sub).toBeVisible()
  await expect(sub.locator('[role="menuitem"]').first()).toBeFocused()
  await sub.locator('[role="menuitem"]').first().click()
  await expect(sub).not.toBeVisible()
  await expect(menu).not.toBeVisible()
  expect(await page.evaluate(() => window.__closes)).toBe(1)
})

