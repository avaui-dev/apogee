  await expect(label.locator('.apogee-file-hint')).toContainText('larger than 1 MB')
  await drop('ok.png', 'image/png', 10)
  expect(await input.evaluate((i) => i.files.length)).toBe(1)
  expect(await label.getAttribute('data-invalid')).toBe('false')
  await expect(label.locator('.apogee-file-hint')).toHaveText('PNG or JPG, up to 1 MB')
