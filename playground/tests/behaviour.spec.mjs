  const drop = (name, type, size) =>
    label.evaluate(
      (el, { name, type, size }) => {
        const dt = new DataTransfer()
        dt.items.add(new File([new Uint8Array(size)], name, { type }))
        el.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: dt }))
      },
      { name, type, size },
    )
