test('popover width="trigger" matches the trigger and escapes overflow clipping', async ({ page }) => {
  await page.goto('/docs/popover')
  const trigger = page.locator('[data-apogee-popover="clip"] > button').first()
  await trigger.click()
  const panel = page.locator(`#${await trigger.getAttribute('popovertarget')}`)
  await expect(panel).toBeVisible()
  await settled(panel)
  const t = await trigger.boundingBox(), p = await panel.boundingBox()
  expect(Math.abs(p.width - t.width)).toBeLessThan(1)
  const hit = await page.evaluate(([x, y, id]) => document.elementFromPoint(x, y)?.closest('#' + id) !== null, [p.x + p.width / 2, p.y + p.height - 4, await panel.getAttribute('id')])
  expect(hit).toBe(true)
})

