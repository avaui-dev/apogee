test('dropdown submenu: ArrowLeft and Escape return focus to the triggers; hover then click keeps it open', async ({ page }) => {
  await page.goto('/docs/dropdown')
  const root = page.locator('.apogee-dropdown', { has: page.locator('.apogee-dropdown-sub') }).first()
  const trigger = root.locator('> button')
  const menu = root.locator('> [role="menu"]')
  const subTrigger = root.locator('.apogee-dropdown-sub > [role="menuitem"]').first()
  const sub = root.locator('.apogee-dropdown-sub > [role="menu"]').first()
  await trigger.focus()
  await trigger.press('ArrowDown')
  await subTrigger.focus()
  await subTrigger.press('ArrowRight')
  await expect(sub.locator('[role="menuitem"]').first()).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(sub).not.toBeVisible()
  await expect(subTrigger).toBeFocused()
  await subTrigger.press('ArrowRight')
  await expect(sub.locator('[role="menuitem"]').first()).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(sub).not.toBeVisible()
  await expect(subTrigger).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()
  await expect(trigger).toBeFocused()
  // Mouse: hover opens the submenu; the click that follows must not toggle it closed.
  // Scroll first: a scroll during hover moves the anchored panel from under the pointer.
  await root.scrollIntoViewIfNeeded()
  await trigger.click()
  await subTrigger.hover()
  await expect(sub).toBeVisible()
  await subTrigger.click()
  await page.waitForTimeout(300)
  await expect(sub).toBeVisible()
})

