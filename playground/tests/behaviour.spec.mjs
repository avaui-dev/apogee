// Wait for a popover panel's open transition so its box is at rest.
const settled = (panel) => panel.evaluate((el) => Promise.all(el.getAnimations().map((a) => a.finished)))

test('popover placement end sits after the trigger, and before it in RTL', async ({ page }) => {
  for (const [path, after] of [['/docs/popover', true], ['/rtl', false]]) {
    await page.goto(path)
    const trigger = page.locator('[data-apogee-popover="end"] > button').first()
    await trigger.click()
    const panel = page.locator(`#${await trigger.getAttribute('popovertarget')}`)
    await expect(panel).toBeVisible()
    await settled(panel)
    const t = await trigger.boundingBox(), p = await panel.boundingBox()
    if (after) expect(p.x).toBeGreaterThanOrEqual(t.x + t.width - 1)
    else expect(p.x + p.width).toBeLessThanOrEqual(t.x + 1)
    await page.keyboard.press('Escape')
  }
})

