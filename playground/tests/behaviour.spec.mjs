test('custom select: keyboard choice updates the native select, fires change and submits with the form', async ({ page }) => {
  await page.goto('/docs/select')
  const root = page.locator('.apogee-select[data-custom]').first()
  const native = root.locator('select')
  const trigger = root.locator('button[aria-haspopup="listbox"]')
  await expect(native).toBeHidden()
  await page.evaluate(() => { window.__changed = 0; document.addEventListener('change', () => window.__changed++, true) })
  await trigger.click()
  const list = page.locator(`#${await trigger.getAttribute('aria-controls')}`)
  await expect(list).toBeVisible()
  await expect(list.locator('[role="option"]').first()).toBeFocused() // opening focuses the current option
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(list).not.toBeVisible()
  // Focus opens on the first enabled option; two ArrowDowns land on the third listbox option.
  const picked = list.locator('[role="option"]').nth(2)
  const expected = await picked.getAttribute('data-value')
  expect(await native.inputValue()).toBe(expected)
  expect(await page.evaluate(() => window.__changed)).toBe(1)
  await expect(trigger).toContainText(await picked.getAttribute('data-label'))
  const name = await native.getAttribute('name')
  expect(await root.evaluate((r, n) => new FormData(r.closest('form')).get(n), name)).toBe(expected)
  // Clicking the field label focuses the trigger, not the hidden select.
  await page.locator(`label[for="${await native.getAttribute('id')}"]`).click()
  await expect(trigger).toBeFocused()
})

test('combobox skips disabled options and commits the value of a rich option', async ({ page }) => {
  await page.goto('/docs/combobox')
  const root = page.locator('.apogee-combobox', { has: page.locator('[role="option"][aria-disabled="true"]') }).first()
  const input = root.locator('[role="combobox"]')
  await page.evaluate(() => { window.__sel = []; document.addEventListener('apogee:combobox-select', (e) => window.__sel.push(e.detail)) })
  await input.click()
  const list = page.locator(`#${await input.getAttribute('aria-controls')}`)
  await expect(list).toBeVisible()
  await input.press('ArrowDown') // from the first enabled option, skipping the disabled one
  const active = list.locator('[aria-selected="true"]')
  await expect(active).not.toHaveAttribute('aria-disabled', 'true')
  await input.press('Enter')
  const sel = await page.evaluate(() => window.__sel)
  expect(sel.length).toBe(1)
  expect(sel[0].value).not.toBe(sel[0].label)
  expect(await input.inputValue()).toBe(sel[0].label)
})

test('dropdown submenu: ArrowLeft and Escape return focus to the triggers; hover then click keeps it open', async ({ page }) => {
  await page.goto('/docs/dropdown')
  const root = page.locator('.apogee-dropdown', { has: page.locator('.apogee-dropdown-sub') }).first()
  const trigger = root.locator('> button')
  const menu = root.locator('> [role="menu"]')
  const subTrigger = root.locator('.apogee-dropdown-sub > [role="menuitem"]').first()
  const sub = root.locator('.apogee-dropdown-sub > [role="menu"]').first()
  await trigger.focus()
  await trigger.press('ArrowDown')
  await subTrigger.focus()
  await subTrigger.press('ArrowRight')
  await expect(sub.locator('[role="menuitem"]').first()).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(sub).not.toBeVisible()
  await expect(subTrigger).toBeFocused()
  await subTrigger.press('ArrowRight')
  await expect(sub.locator('[role="menuitem"]').first()).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(sub).not.toBeVisible()
  await expect(subTrigger).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()
  await expect(trigger).toBeFocused()
  // Mouse: hover opens the submenu; the click that follows must not toggle it closed.
  await trigger.click()
  await subTrigger.hover()
  await expect(sub).toBeVisible()
  await subTrigger.click()
  await page.waitForTimeout(300)
  await expect(sub).toBeVisible()
})

